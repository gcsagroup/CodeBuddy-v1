import { mkdir, readFile, writeFile } from 'node:fs/promises';
import { join } from 'node:path';
import { expect, test } from './fixtures';

test.setTimeout(240_000);

test('Shared skills appear after external installation and persist explicit enable without editing the source', async ({ appPage, isolatedProfileRoot }, testInfo) => {
  const directory = join(isolatedProfileRoot, '.agents', 'skills', 'shared-acceptance');
  const source = '---\nname: shared-acceptance\ndescription: Shared catalog acceptance\n---\nRead this fixture only.';
  await mkdir(directory, { recursive: true });
  await writeFile(join(directory, 'SKILL.md'), source);
  await appPage.getByRole('button', { name: '工具箱', exact: true }).click();
  const card = appPage.getByRole('button', { name: 'shared-acceptance', exact: true });
  await expect(card).toBeVisible();
  await expect(card).toContainText('本机共享技能');
  await expect(card).toContainText('尚未在 CodeBuddy 启用');
  await card.click();
  let detail = appPage.getByRole('dialog', { name: 'shared-acceptance', exact: true });
  await expect(detail.getByRole('button', { name: '使用技能', exact: true })).toBeDisabled();
  await expect(detail.getByRole('button', { name: '编辑', exact: true })).toHaveCount(0);
  await detail.getByRole('button', { name: '启用', exact: true }).click();
  let confirmation = appPage.getByRole('dialog', { name: '启用这个共享技能？', exact: true });
  await expect(confirmation).toBeVisible();
  await confirmation.getByRole('button', { name: '取消', exact: true }).click();
  await expect(card).toContainText('尚未在 CodeBuddy 启用');
  await expect(appPage.getByRole('alert')).toHaveCount(0);
  await appPage.getByRole('switch', { name: /shared-acceptance/ }).click();
  confirmation = appPage.getByRole('dialog', { name: '启用这个共享技能？', exact: true });
  await confirmation.getByRole('button', { name: '取消', exact: true }).click();
  await expect(appPage.getByRole('switch', { name: /shared-acceptance/ })).toBeEnabled();
  await expect(card).toContainText('尚未在 CodeBuddy 启用');
  await expect(appPage.getByRole('alert')).toHaveCount(0);
  await card.click();
  detail = appPage.getByRole('dialog', { name: 'shared-acceptance', exact: true });
  await detail.getByRole('button', { name: '启用', exact: true }).click();
  confirmation = appPage.getByRole('dialog', { name: '启用这个共享技能？', exact: true });
  await confirmation.getByRole('button', { name: '启用', exact: true }).click();
  await expect(card).toContainText('已启用');
  await expect.poll(async () => JSON.parse(await readFile(join(isolatedProfileRoot, '.CodeBuddy', 'backend', 'harness', 'shared-skills.json'), 'utf8')).enabled).toEqual(expect.objectContaining({ [join(directory, 'SKILL.md').toLowerCase()]: true }));
  expect(await readFile(join(directory, 'SKILL.md'), 'utf8')).toBe(source);
  await appPage.reload();
  await appPage.getByRole('button', { name: '工具箱', exact: true }).click();
  await expect(card).toContainText('已启用');
  await card.click();
  detail = appPage.getByRole('dialog', { name: 'shared-acceptance', exact: true });
  await expect(detail.getByRole('button', { name: '使用技能', exact: true })).toBeEnabled();
  await appPage.screenshot({ path: testInfo.outputPath('shared-skill-enabled.png') });
  await detail.getByRole('button', { name: '停用', exact: true }).click();
  await expect(card).toContainText('尚未在 CodeBuddy 启用');
  await expect(appPage.getByRole('dialog', { name: '启用这个共享技能？', exact: true })).toHaveCount(0);
  expect(await readFile(join(directory, 'SKILL.md'), 'utf8')).toBe(source);
});
