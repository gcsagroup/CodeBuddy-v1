import test from 'node:test';
import assert from 'node:assert/strict';
import { createServer } from 'node:http';
import { mkdtemp } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { createHarnessDriver } from '../harness/index.mjs';

test('Ollama cloud output budgets retain route identity, end as limited, and leave the next turn usable', { timeout: 30000 }, async t => {
  const requests = [];
  const server = createServer(async (req, res) => {
    if (req.method === 'GET') {
      res.writeHead(200, { 'content-type': 'application/json' });
      res.end(JSON.stringify({ models: [{ name: 'fixture' }] }));
      return;
    }
    let raw = ''; for await (const chunk of req) raw += chunk;
    const body = JSON.parse(raw); requests.push(body);
    res.writeHead(200, { 'content-type': 'text/event-stream' });
    const first = requests.length === 1;
    const content = first ? 'Partial review at the output limit.' : 'The next turn remains usable.';
    res.end(`data: ${JSON.stringify({ choices: [{ index: 0, delta: { role: 'assistant', content }, finish_reason: first ? 'length' : 'stop' }] })}\n\ndata: [DONE]\n\n`);
  });
  await new Promise(resolve => server.listen(0, '127.0.0.1', resolve));
  t.after(() => new Promise(resolve => server.close(resolve)));
  const nativeFetch = globalThis.fetch;
  t.mock.method(globalThis, 'fetch', (input, init) => {
    const url = new URL(typeof input === 'string' || input instanceof URL ? input : input.url);
    assert.equal(url.hostname, 'ollama.com');
    return nativeFetch(`http://127.0.0.1:${server.address().port}${url.pathname}`, init);
  });
  const provider = { id: 'ollama-budget-fixture', baseUrl: 'https://ollama.com/v1', apiKey: 'fixture-only', contextWindow: 32768 };
  const root = await mkdtemp(join(tmpdir(), 'codebuddy-ollama-budget-'));
  const driver = await createHarnessDriver({ dataDir: root, cwd: root, instructionsHome: root });
  t.after(() => driver.close());
  const { sessionId } = await driver.createSession({ provider, model: 'fixture', options: { maxTokens: 32 } });
  const limited = await driver.prompt(sessionId, 'Review the fixture.');
  assert.equal(requests[0].max_tokens, 32);
  assert.equal(requests[0].max_completion_tokens, undefined);
  assert.equal(limited.stopReason, 'max_tokens', 'An output budget must not be reported as successful completion');
  const route = (await driver.history(sessionId)).events.find(event => event.type === 'request/context').data.provider;
  // Frozen from this fixture's pre-fix route, not regenerated by the new code.
  assert.equal(route, 'codebuddy-5ac317dfbb122bf98c0e', 'Wire compatibility must not change the persisted model route');
  const next = await driver.prompt(sessionId, 'Give me the current status.');
  assert.equal(next.stopReason, 'end_turn');
});
